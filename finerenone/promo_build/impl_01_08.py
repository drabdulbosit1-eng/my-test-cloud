# ---------------------------------------------------------------- helpers
def footer(s, lines, width=850, name="Источники"):
    """Rewrite the 8 pt black footer with `lines`; bottom edge stays at 534 pt."""
    sh = L.shape_named(s, name)
    L.set_lines(sh, lines)
    lib.set_text_color(sh, BLACK, size=8)
    n = sum(n_lines([(t, False)], width, 8) for t in lines)
    h = n * FOOT_LINE + 2
    sh.top, sh.height, sh.width = Pt(FOOT_BOTTOM - h), Pt(h), Pt(width)
    return sh


def abbr(s, text, name="Сокращения"):
    """Abbreviation line (10 pt, black): rewrite the existing shape or add it at y 494."""
    try:
        sh = L.shape_named(s, name)
    except KeyError:
        return lib.add_text(s, 36, 494, 850, 19, [[(text, 10, False, BLACK)]], name=name)
    L.set_lines(sh, [text])
    lib.set_text_color(sh, BLACK, size=10)
    return sh


def notes_prepend(s, text):
    """Put `text` in front of the first paragraph of the notes."""
    p = s.notes_slide.notes_text_frame.paragraphs[0]
    t = p._p.findall(qn("a:r"))[0].find(qn("a:t"))
    t.text = text + " " + t.text


def notes_add(s, *blocks):
    """Append blocks as separate paragraphs, each after an empty paragraph (as in the original notes)."""
    tf = s.notes_slide.notes_text_frame
    if not tf.paragraphs[-1].text.strip():
        raise ValueError("notes end with an empty paragraph")
    for b in blocks:
        tf.add_paragraph()
        tf.add_paragraph().text = b


def notes_append(s, text):
    """Append a sentence to the last paragraph of the notes."""
    p = s.notes_slide.notes_text_frame.paragraphs[-1]
    runs = p._p.findall(qn("a:r"))
    t = runs[-1].find(qn("a:t"))
    t.text = t.text + " " + text


def notes_insert_after(s, anchor, text):
    """Insert `text` after the sentence `anchor` (found as plain text, NBSP-insensitive)."""
    L.rep(s, anchor, anchor + " " + text, notes=True)


def plate(s, x, y, w, h, color, text, size=17, name=None):
    return lib.bar(s, x, y, w, h, color, text, size=size, name=name, bold=True)


def card_text(s, x, y, w, h, paras, name, fill=CARD, ml=10, mr=10, mt=4, mb=4, anchor="m"):
    """Grey rounded card that carries its own text (paras as in lib.add_text)."""
    c = lib.card(s, x, y, w, h, name=name, fill=fill)
    lib.add_text(s, x, y, w, h, paras, anchor=anchor, name=name, shape=c, margin=0)
    tf = c.text_frame
    tf.margin_left, tf.margin_right, tf.margin_top, tf.margin_bottom = Pt(ml), Pt(mr), Pt(mt), Pt(mb)
    return c


def chev_down(s, cx, cy, vw=22, vh=9, name=None):
    """Grey chevron pointing down, visual size vw x vh, centred at (cx, cy)."""
    sh = lib.chevron(s, cx - vh / 2, cy - vw / 2, w=vh, h=vw, name=name, color=CHEV)
    sh.rotation = 90
    return sh


def recolor_line(sh, color):
    """Change the colour of a connector / line shape."""
    for c in sh._element.iter(qn("a:srgbClr")):
        c.set("val", color)


def to_black(sh, bold=None):
    """Make all text of a shape black (runs and paragraph defaults), optionally bold."""
    lib.set_text_color(sh, BLACK, bold=bold)
    for c in sh._element.find(qn("p:txBody")).iter(qn("a:srgbClr")):
        c.set("val", BLACK)


def drop(s, *names):
    """Delete shapes by name (every shape with that name)."""
    for n in names:
        found = lib.find_shapes(s, n)
        if not found:
            raise KeyError(n)
        for sh in found:
            lib.delete_shape(sh)


