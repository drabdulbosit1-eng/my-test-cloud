def chain_card(s, x, y, w, head, head_color, rows, key):
    """Plate + grey card with `rows` (list of (text, bold)) separated by grey down-chevrons.
    Row pitch: 20 pt text + 16 pt gap. Returns the y of the bottom edge."""
    plate(s, x, y, w, 26, head_color, head, size=16, name="Плашка: " + key)
    h = 6 + 20 * len(rows) + 16 * (len(rows) - 1) + 6
    c = lib.card(s, x, y + 26, w, h, name="Карточка: " + key)
    yy = y + 26 + 6
    for i, (text, bold) in enumerate(rows):
        lib.add_text(s, x + 12, yy, w - 24, 20, [[(text, 16, bold, BLACK)]], name="%s: шаг %d" % (key, i + 1))
        if i < len(rows) - 1:
            chev_down(s, x + w / 2, yy + 20 + 8, name="%s: шеврон %d" % (key, i + 1))
        yy += 36
    return y + 26 + h


