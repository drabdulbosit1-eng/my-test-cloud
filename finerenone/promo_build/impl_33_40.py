# ----------------------------------------------------------------------------- helpers
def nb(s):
    """Non-breaking spaces between a number or a sign and its unit, after short prepositions
    before a number or an inequality sign."""
    s = re.sub(r"(?<=[\d%]) (?=(?:мг|мл|мм|ммоль|мкмоль|нед|мес|лет|года|год|кг|и\b))", NBSP, s)
    s = re.sub(r"\b(до|и|на|от|в|при|с|у) (?=[\d≤≥<>])", lambda m: m.group(1) + NBSP, s, flags=re.I)
    s = re.sub(r"(?<=[≤≥<>]) (?=\d)", "", s)
    s = re.sub(r"(?<=\d) (?=\d{3}\b)", NBSP, s)
    s = s.replace("рСКФ ", "рСКФ" + NBSP).replace("мм рт. ст.", "мм" + NBSP + "рт." + NBSP + "ст.")
    return s


def geom(sh, x=None, y=None, w=None, h=None):
    if x is not None:
        sh.left = Pt(x)
    if y is not None:
        sh.top = Pt(y)
    if w is not None:
        sh.width = Pt(w)
    if h is not None:
        sh.height = Pt(h)
    return sh


def by_name(slide, name):
    return [sh for sh in iter_shapes(slide.shapes) if sh.name == name]


def one(slide, name):
    r = by_name(slide, name)
    if len(r) != 1:
        raise KeyError(f"{name!r}: {len(r)} shapes")
    return r[0]


def drop(slide, name):
    for sh in by_name(slide, name):
        delete_shape(sh)


def recolor_text(sh, color, bold=None, size=None):
    for r in sh._element.iter(qn("a:r")):
        style_rpr(get_rpr(r), color=color, bold=bold, size=size)


def recolor_fill(sh, color):
    sh.fill.solid()
    sh.fill.fore_color.rgb = RGBColor.from_string(color)


def recolor_line(sh, color, width=None):
    sh.line.color.rgb = RGBColor.from_string(color)
    if width is not None:
        sh.line.width = Pt(width)


def set_adj(sh, radius_pct):
    """Corner radius of a rounded rectangle as a share of the short side (0.1667 = default)."""
    sh.adjustments[0] = radius_pct


def put_before(new_sh, ref_sh):
    """Move `new_sh` right under `ref_sh` in z-order (drawn before it)."""
    ref_sh._element.addprevious(new_sh._element)


def to_back(slide, sh):
    slide.shapes._spTree.insert(2, sh._element)


def shape_text(slide, sh, paras, anchor="t", margins=(12, 10, 12, 10), spacing=0.9, after=None):
    """Text inside an existing shape. paras: list of paragraphs; each a list of runs
    (text, size, bold, color) or a dict as in lib.add_text."""
    add_text(slide, 0, 0, 0, 0, paras, anchor=anchor, shape=sh, margin=0, line_spacing=spacing,
             space_after=after)
    tf = sh.text_frame
    tf.margin_left, tf.margin_top, tf.margin_right, tf.margin_bottom = (Pt(m) for m in margins)
    return sh


def txt(slide, x, y, w, h, paras, name, anchor="t", spacing=0.9, after=None):
    return add_text(slide, x, y, w, h, paras, anchor=anchor, name=name, line_spacing=spacing,
                    space_after=after)


def plate(slide, x, y, w, h, color, paras, name, anchor="m", margins=(12, 2, 8, 2), radius=None):
    """Rounded plate with text; radius in pt (default: 16,7% of the short side)."""
    r = radius if radius is not None else min(w, h) / 6
    sh = add_box(slide, x, y, w, h, fill=color, radius=r, name=name)
    shape_text(slide, sh, paras, anchor=anchor, margins=margins, spacing=0.9)
    return sh


def grey_card(slide, x, y, w, h, name, fill=CARD, radius=None):
    r = radius if radius is not None else min(w, h) / 6
    return add_box(slide, x, y, w, h, fill=fill, radius=min(r, 8), name=name)


def lines_of(paras, w, size):
    return sum(M.n_lines(p, w, size) for p in paras)


def footers(slide, abbr, sources, abbr_size=10):
    """Rewrite 'Источники' (8 pt, bottom edge fixed, grows upwards) and 'Сокращения' (10 pt, sits
    above the sources). Both black. `abbr` or `sources` may be None (line not touched)."""
    top = BODY_BOTTOM
    if sources is not None:
        src = L.shape_named(slide, "Источники")
        L.set_lines(src, sources)
        n = sum(M.n_lines([(p, False)], 850, 8) for p in sources)
        h = max(16.0, round(n * 9.8 + 2, 1))
        geom(src, x=36, y=BODY_BOTTOM - h, w=850, h=h)
        for r in src._element.iter(qn("a:r")):
            style_rpr(get_rpr(r), size=8, color=BLACK)
        top = BODY_BOTTOM - h
    if abbr is not None:
        ab = L.shape_named(slide, "Сокращения")
        L.set_lines(ab, [abbr])
        na = M.n_lines([(abbr, False)], 850, abbr_size)
        ha = round(na * 12.4, 1)
        top = min(494.0, top - 3 - ha)
        geom(ab, x=36, y=top, w=850, h=ha)
        for r in ab._element.iter(qn("a:r")):
            style_rpr(get_rpr(r), color=BLACK)
    return top


def old_paras(slide):
    """Non-empty paragraphs of the current notes."""
    return [p for p in L.notes_text(slide).split("\n") if p.strip()]


def put_notes(slide, story, visit=None, asks=()):
    """Notes: story paragraphs (the last one ends with the transition), then the visit phrase,
    then the 'Если врач спросит' blocks. Paragraphs are separated by an empty paragraph."""
    paras = [re.sub(r"\s{2,}", " ", p).strip() for p in story]
    if visit:
        paras.append(visit)
    paras += list(asks)
    L.set_notes(slide, "\n\n".join(paras))


