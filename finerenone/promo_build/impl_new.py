def polyline(s, pts, name, color=LINE, width=3.0, arrow=True):
    """Open polyline with an arrow head at the end (freeform)."""
    fb = s.shapes.build_freeform(Pt(pts[0][0]), Pt(pts[0][1]), scale=1.0)
    fb.add_line_segments([(Pt(x), Pt(y)) for x, y in pts[1:]], close=False)
    sh = fb.convert_to_shape()
    sh.fill.background()
    st = sh._element.find(qn("p:style"))
    if st is not None:
        sh._element.remove(st)
    sh.line.color.rgb = RGBColor.from_string(color)
    sh.line.width = Pt(width)
    if arrow:
        ln = sh.line._get_or_add_ln()
        tail = etree.SubElement(ln, qn("a:tailEnd"))
        tail.set("type", "triangle")
        tail.set("w", "med")
        tail.set("len", "med")
    sh.name = name
    return sh


