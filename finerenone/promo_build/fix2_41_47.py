def s46(prs):
    """Решение FDA: одна строка в нижней карточке по центру карточки."""
    s = L.S(prs, 46)
    bg = L.shape_named(s, "США_фон_3")
    tx = L.shape_named(s, "США_текст_3")
    tx.top = bg.top
    tx.height = bg.height
    tx.text_frame.vertical_anchor = MSO_ANCHOR.MIDDLE
    # у низкой карточки скругление было мельче, чем у двух верхних (радиус считается от меньшей стороны)
    for gd in bg._element.iter("{http://schemas.openxmlformats.org/drawingml/2006/main}gd"):
        if gd.get("name") == "adj":
            gd.set("fmla", "val %d" % round(Emu(L.shape_named(s, "США_фон_1").height).pt * 2777 / Emu(bg.height).pt))


