def _set_y(sh, y):
    sh.top = Emu(int(round(y * 12700)))


def _set_h(sh, h):
    sh.height = Emu(int(round(h * 12700)))


def s33(prs):
    s = L.S(prs, 33)
    # единая формула контроля калия: слайд говорит «после начала лечения, его возобновления или повышения дозы»,
    # а в заметках «начало» выпало
    L.rep(s, "Через четыре недели после возобновления или повышения дозы повторяют калий и рСКФ.",
          "Через четыре недели после начала лечения, его возобновления или повышения дозы повторяют калий и рСКФ.",
          notes=True, count=1)


